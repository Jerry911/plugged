    /** the grid x of an upstream x */
    static double ux(double x) {
        return SymbolShapes.rd(1 - U + U * x);
    }

    /** the grid y of an upstream y (the centre line is y = 0) */
    static double uy(double y) {
        return SymbolShapes.rd(12 + U * y);
    }


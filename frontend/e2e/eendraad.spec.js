import {test, expect, t} from './fixtures.js'
import {node, project, withCircuit} from './data.js'

const circuits = (saved) => saved.een[0].tree[0].children[0].children
const btn = (page, id) => page.locator('#' + id)

test.describe('building the schema', () => {
    test('circuits and elements are added from the palette in the right place', async ({page, app, backend}) => {
        await app.open(backend)
        await app.treeRow(t('board.boardLabel')).click()
        await app.add('kring')
        await app.add('kring')
        const saved1 = await app.save(backend)
        expect(circuits(saved1).map((circuit) => circuit.label)).toEqual(['A', 'B'])
        // the new circuit is selected; elements go into the selected circuit
        await app.add('stopcontact')
        // (a lichtpunt hangs behind a switch, not directly under a circuit: a wall lamp does)
        await app.add('wandlamp')
        const saved = await app.save(backend)
        expect(circuits(saved)[1].children.map((n) => n.type)).toEqual(['stopcontact', 'wandlamp'])
        expect(circuits(saved)[0].children).toHaveLength(0)
    })
    test('an element that does not fit under the selection is refused, unless the hierarchy is free', async ({page, app, backend, dialogs}) => {
        await app.open(backend)
        await app.treeRow(t('board.connectionLabel')).click()
        await app.add('stopcontact')
        expect(dialogs.messages.at(-1)).toContain(t('oneWire.onlyUnder', {name: t('symbols.stopcontact'), parents: ''}).split(':')[0])
        await page.locator('#eds-free-hierarchy').check()
        await app.add('stopcontact')
        const saved = await app.save(backend)
        expect(saved.een[0].tree[0].children.map((n) => n.type)).toEqual(['bord', 'stopcontact'])
    })
    test('without any selection an element is asked to be put somewhere sensible', async ({page, app, backend, dialogs}) => {
        await app.open(backend, project({een: [{id: 'e1', name: 'Blad 1', tree: [node('A', 'aansluiting')]}]}))
        await app.add('stopcontact')
        expect(dialogs.messages.at(-1)).toBe(t('oneWire.selectParentFirst'))
    })
    test('the palette can be searched', async ({page, app, backend}) => {
        await app.open(backend)
        const search = page.locator('#eds-palette-search')
        await search.fill('oven')
        await expect(page.locator('.pal details')).toHaveCount(1)
        await expect(app.paletteButton('oven')).toBeVisible()
        await search.fill('zzzz')
        await expect(page.locator('.pal details')).toHaveCount(0)
        await search.fill('')
        expect(await page.locator('.pal details').count()).toBeGreaterThan(3)
    })
    test('a circuit gets the next free letter', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        await app.treeRow(t('board.boardLabel')).click()
        await app.add('kring')
        const saved = await app.save(backend)
        expect(circuits(saved).map((circuit) => circuit.label)).toEqual(['K', 'A'])
    })
    test('wide boards continue on a second sheet', async ({page, app, backend}) => {
        const ks = Array.from({length: 16}, (_, i) => node('K' + i, 'kring', [node('S' + i, 'stopcontact')], {label: String.fromCharCode(65 + i), info: 'B16 2,5mm²'}))
        await app.open(backend, project({een: [{id: 'e1', name: 'Groot', tree: [node('A', 'aansluiting', [node('B', 'bord', ks)])]}]}))
        await expect(page.locator('div[id^="eds-sheet-"]')).toHaveCount(2)
    })
})

test.describe('editing properties', () => {
    test('a circuit: letter and electrical properties show up in the spec text of the circuit', async ({page, app, backend}) => {
        await app.open(backend)
        await app.treeRow(t('board.boardLabel')).click()
        await app.add('kring')
        await page.locator('#eds-field-amp').fill('20')
        await page.locator('#eds-field-curve').fill('C')
        await page.locator('#eds-field-polen').fill('4')
        await page.locator('#eds-field-kabel').fill('XVB 3G4')
        await page.locator('#eds-field-tekst').fill('Oven')
        await page.locator('#eds-label').fill('Z')
        await expect(page.locator('#eds-specs')).toHaveCount(0)
        const saved = await app.save(backend)
        expect(circuits(saved)[0]).toMatchObject({label: 'Z', info: 'C20 4P XVB 3G4'})
        expect(circuits(saved)[0].p).toMatchObject({amp: '20', curve: 'C', polen: '4', tekst: 'Oven'})
        await expect(page.locator('svg.sheet').first()).toContainText('Oven')
    })
    test('an element: name, specs and type', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        await app.treeRow('Keuken stopcontact').click()
        await expect(page.locator('#eds-props')).toBeVisible()
        await page.locator('#eds-label').fill('Living stopcontact')
        await page.locator('#eds-specs').fill('3G2,5')
        await page.locator('#eds-type').selectOption('stopcontact2')
        const saved = await app.save(backend)
        expect(circuits(saved)[0].children[0]).toMatchObject({label: 'Living stopcontact', info: '3G2,5', type: 'stopcontact2'})
    })
    test('the board can be marked as earthed', async ({page, app, backend}) => {
        await app.open(backend)
        await app.treeRow(t('board.boardLabel')).click()
        await page.locator('#eds-earthed').check()
        const saved = await app.save(backend)
        expect(saved.een[0].tree[0].children[0].p.geaard).toBe(true)
    })
    test('Eigenschappen can be closed with the cross', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        await expect(btn(page, 'eds-close')).toHaveCount(0)
        await app.treeRow('Keuken stopcontact').click()
        await btn(page, 'eds-close').click()
        await expect(page.locator('#eds-props')).toHaveCount(0)
    })
    test('a socket can be waterproof: the drawing shows an h', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        await app.treeRow('Keuken stopcontact').click()
        const before = await page.locator('svg.sheet').first().locator('text', {hasText: /^h$/}).count()
        await btn(page, 'eds-waterproof').check()
        await expect(page.locator('svg.sheet').first().locator('text', {hasText: /^h$/})).toHaveCount(before + 1)
        const saved = await app.save(backend)
        expect(circuits(saved)[0].children[0].p.h).toBe(true)
        await app.treeRow('Gang licht').click()
        await expect(btn(page, 'eds-waterproof')).toHaveCount(0)
    })
    test('an inverter has a details box under the symbol, one line per fact', async ({page, app, backend}) => {
        await app.open(backend, project({een: [{id: 'e1', name: 'PV', tree: [node('A', 'aansluiting', [node('B', 'bord', [node('K', 'kring', [node('O', 'omvormer', [], {label: 'PV-omvormer'})], {info: 'B16'})])])]}]}))
        await app.treeRow('PV-omvormer').click()
        await page.locator('#eds-details').fill('Merk: Huawei\nType: SUN2000-6KTL')
        await expect(page.locator('svg.sheet').first()).toContainText('Merk: Huawei')
        await expect(page.locator('svg.sheet').first()).toContainText('Type: SUN2000-6KTL')
    })
})

test.describe('arranging elements', () => {
    const two = () => project({een: [{id: 'e1', name: 'Blad 1', tree: [node('A', 'aansluiting', [node('B', 'bord', [node('K1', 'kring', [node('S1', 'stopcontact', [], {label: 'Eerste'})], {label: 'A'}), node('K2', 'kring', [node('S2', 'stopcontact', [], {label: 'Tweede'})], {label: 'B'})])])]}]})
    test('move earlier / later, duplicate and delete', async ({page, app, backend}) => {
        await app.open(backend, two())
        await app.drawn('K1').click()
        await btn(page, 'eds-later').click()
        let saved = await app.save(backend)
        expect(circuits(saved).map((circuit) => circuit.id)).toEqual(['K2', 'K1'])
        await btn(page, 'eds-earlier').click()
        saved = await app.save(backend)
        expect(circuits(saved).map((circuit) => circuit.id)).toEqual(['K1', 'K2'])
        await app.treeRow('Eerste').click()
        await btn(page, 'eds-duplicate').click()
        saved = await app.save(backend)
        expect(circuits(saved)[0].children.map((n) => n.label)).toEqual(['Eerste', 'Eerste'])
        expect(new Set(circuits(saved)[0].children.map((n) => n.id)).size).toBe(2)
        await page.keyboard.press('Delete')
        saved = await app.save(backend)
        expect(circuits(saved)[0].children).toHaveLength(1)
    })
    test('one level lower puts an element under the previous one, one level higher takes it out again', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        await app.treeRow('Gang licht').click()
        await btn(page, 'eds-indent').click()
        let saved = await app.save(backend)
        expect(circuits(saved)[0].children).toHaveLength(1)
        expect(circuits(saved)[0].children[0].children.map((n) => n.id)).toEqual(['L'])
        await btn(page, 'eds-outdent').click()
        saved = await app.save(backend)
        expect(circuits(saved)[0].children.map((n) => n.id)).toEqual(['S', 'L'])
    })
    test('Delete and Backspace remove the selection, but not while typing in a field', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        await app.treeRow('Gang licht').click()
        await page.locator('#eds-label').focus()
        await page.keyboard.press('Backspace') // edits the text, deletes nothing
        await expect(app.treeRow('Gang lich')).toBeVisible()
        await page.locator('#eds-tree').click({position: {x: 2, y: 2}}).catch(() => {})
        await app.treeRow('Keuken stopcontact').click()
        await page.keyboard.press('Backspace')
        await expect(page.locator('#eds-tree')).not.toContainText('Keuken stopcontact')
    })
    test('the trash buttons delete an element with everything below it', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        await app.drawn('K').click()
        await btn(page, 'eds-delete').click()
        const saved = await app.save(backend)
        expect(circuits(saved)).toHaveLength(0)
        await expect(page.locator('#eds-props')).toHaveCount(0)
    })
    test('a trash can appears on the selected symbol in the drawing', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        await expect(btn(page, 'eds-drawing-delete')).toHaveCount(0)
        await app.drawn('S').click()
        await expect(btn(page, 'eds-drawing-delete')).toHaveCount(1)
        await btn(page, 'eds-drawing-delete').click()
        await expect(page.locator('#eds-tree')).not.toContainText('Keuken stopcontact')
        await expect(page.locator('#eds-tree')).toContainText('Gang licht')
    })
    test('symbols are turned in steps and a full turn comes back to the start; distribution parts cannot be turned', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        await app.drawn('K').click()
        await expect(btn(page, 'eds-rotate-cw')).toBeDisabled()
        await app.treeRow('Keuken stopcontact').click()
        await btn(page, 'eds-rotate-cw').click()
        await expect(btn(page, 'eds-rotation')).toHaveText('15°')
        await btn(page, 'eds-rotate-ccw').click()
        await btn(page, 'eds-rotate-ccw').click()
        await expect(btn(page, 'eds-rotation')).toHaveText('345°')
        for (let i = 0; i < 24; i++) await btn(page, 'eds-rotate-cw').click()
        await expect(btn(page, 'eds-rotation')).toHaveText('345°')
        await btn(page, 'eds-rotate-cw').click()
        await btn(page, 'eds-rotate-cw').click()
        const saved = await app.save(backend)
        expect(circuits(saved)[0].children[0].r).toBe(15)
        await expect(page.locator('svg.sheet').first().locator('g[transform^="rotate(15 "]').first()).toBeVisible()
    })
    test('empty symbols are inserted after (under) and before the selected symbol; the Type list only offers what fits', async ({page, app, backend}) => {
        await app.open(backend, project({een: [{id: 'e1', name: 'Blad 1', tree: [node('A', 'aansluiting', [node('B', 'bord', [node('K', 'kring', [node('S', 'schakelaar', [node('L', 'lichtpunt')])])])])]}]}))
        await app.drawn('S').click()
        await btn(page, 'eds-insert-after').click()
        const type = page.locator('#eds-type')
        await expect(type).toHaveValue('leeg')
        await expect(type.locator('option').first()).toHaveText(t('oneWire.chooseSymbol'))
        const options = await type.locator('option').allTextContents()
        expect(options).toContain('Stopcontact (aarding)')
        expect(options).not.toContain('Verdeelbord') // a board does not hang under a switch
        // an empty symbol cannot be extended until it has a type
        await expect(btn(page, 'eds-insert-after')).toBeDisabled()
        await expect(btn(page, 'eds-insert-before')).toBeDisabled()
        await type.selectOption('stopcontact')
        let saved = await app.save(backend)
        const socket = circuits(saved)[0].children[0]
        expect(socket.children.map((n) => n.type)).toEqual(['lichtpunt', 'stopcontact'])
        await app.drawn('S').click()
        await btn(page, 'eds-insert-before').click()
        await expect(type).toHaveValue('leeg')
        saved = await app.save(backend)
        const circuit = circuits(saved)[0]
        expect(circuit.children).toHaveLength(1)
        expect(circuit.children[0].type).toBe('leeg')
        expect(circuit.children[0].children.map((n) => n.id)).toEqual(['S']) // the switch moved under the new element
    })
    test('nothing can be inserted above the top element, unless the hierarchy is free', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        await app.treeRow(t('board.connectionLabel')).click()
        await expect(btn(page, 'eds-insert-before')).toBeDisabled()
        await page.locator('#eds-free-hierarchy').check()
        await expect(btn(page, 'eds-insert-before')).toBeEnabled()
    })
    test('the Tak button puts a new branch next to the selected circuit (A -> B)', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        await app.drawn('K').click()
        await btn(page, 'eds-insert-branch').click()
        await expect(page.locator('#eds-type')).toHaveValue('leeg')
        const saved = await app.save(backend)
        expect(circuits(saved)).toHaveLength(2)
    })
})

test.describe('the drawing', () => {
    test('clicking a circuit letter or a symbol in the drawing selects it in the list', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        await app.drawn('S').click()
        await expect(page.locator('#eds-label')).toHaveValue('Keuken stopcontact')
        await app.drawn('K').click()
        await expect(page.locator('#eds-label')).toHaveValue('K')
    })
    test('levels can be folded in the Opbouw list, and selecting a hidden element unfolds them', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        const tree = page.locator('#eds-tree')
        await expect(tree).toContainText('Keuken stopcontact')
        await btn(page, 'eds-toggle-K').click()
        await expect(tree).not.toContainText('Keuken stopcontact')
        await expect(tree).toContainText('(+2)')
        await btn(page, 'eds-toggle-K').click()
        await expect(tree).toContainText('Keuken stopcontact')
        await btn(page, 'eds-toggle-K').click()
        await app.drawn('S').click()
        await expect(tree).toContainText('Keuken stopcontact')
    })
    test('zoom buttons scale the schema', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
                await expect(page.locator('#eds-zoom-1-reset')).toHaveText('100%')
        await page.locator('#eds-zoom-1-in').click()
        await expect(page.locator('#eds-zoom-1-reset')).not.toHaveText('100%')
        await page.locator('#eds-zoom-1-reset').click()
        await expect(page.locator('#eds-zoom-1-reset')).toHaveText('100%')
        await page.locator('#eds-zoom-1-out').click()
        await expect(page.locator('#eds-zoom-1-reset')).not.toHaveText('100%')
    })
    test('zooming keeps the sheet you zoomed on in view: zoomed in it fills the screen, the next sheet stays below it', async ({page, app, backend}) => {
        // a board with so many circuits that the schema takes several sheets
        const circuits = Array.from({length: 40}, (_, index) => node('K' + index, 'kring', [node('S' + index, 'stopcontact')], {p: {}}))
        await app.open(backend, project({een: [{id: 'e1', name: 'Groot', tree: [node('A', 'aansluiting', [node('B', 'bord', circuits)])]}]}))
        const sheets = page.locator('[id^="eds-sheet-"][id$="-drawing"]')
        expect(await sheets.count()).toBeGreaterThanOrEqual(3)
        const viewport = page.viewportSize(),
            sheet = (n) => page.locator('#eds-sheet-' + n)
        await sheet(2).scrollIntoViewIfNeeded()
        await page.locator('#eds-zoom-2-in').click()
        await expect(page.locator('#eds-zoom-2-reset')).toHaveText('150%')
        // the zoomed sheet is at the top of the screen and its drawing is as high as the screen: no half of another sheet
        const zoomed = await sheet(2).boundingBox()
        expect(zoomed.y).toBeGreaterThanOrEqual(0)
        expect(zoomed.y).toBeLessThan(30)
        const pane = await sheet(2).locator('.zoomscroll').boundingBox()
        expect(pane.height).toBeGreaterThan(viewport.height - 40)
        expect((await sheet(3).boundingBox()).y).toBeGreaterThanOrEqual(viewport.height - 20)
        expect((await sheet(1).boundingBox()).y + (await sheet(1).boundingBox()).height).toBeLessThanOrEqual(5)
        // zooming further stays on the same sheet
        await page.locator('#eds-zoom-2-in').click()
        expect((await sheet(2).boundingBox()).y).toBeLessThan(30)
        // back to 100%: the sheet is still on the screen
        await page.locator('#eds-zoom-2-reset').click()
        await expect(page.locator('#eds-zoom-2-reset')).toHaveText('100%')
        const back = await sheet(2).boundingBox()
        expect(back.y).toBeLessThan(viewport.height)
        expect(back.y + back.height).toBeGreaterThan(0)
    })
    test('dragging a symbol from the palette onto the drawing inserts it: right half after, left half before', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        await page.locator('#eds-palette-search').fill('Wandlamp')
        const lamp = app.paletteButton('wandlamp')
        const dragOnto = async (id, fraction) => {
            const box = await app.drawn(id).boundingBox()
            await lamp.hover()
            await page.mouse.down()
            await page.mouse.move(box.x + 2, box.y + 2, {steps: 3}) // the first moves start the drag
            await page.mouse.move(box.x + box.width * fraction, box.y + box.height / 2, {steps: 8})
            await expect(page.locator('#eds-drop-preview')).toBeVisible()
            await page.mouse.up()
            await expect(page.locator('#eds-drop-preview')).toHaveCount(0)
        }
        await dragOnto('S', 0.75)
        let saved = await app.save(backend)
        expect(circuits(saved)[0].children[0].children.map((n) => n.type)).toEqual(['wandlamp'])
        await dragOnto('L', 0.15)
        saved = await app.save(backend)
        const circuit = circuits(saved)[0]
        expect(circuit.children.map((n) => n.type)).toEqual(['stopcontact', 'wandlamp'])
        expect(circuit.children[1].children.map((n) => n.id)).toEqual(['L']) // the light now hangs under the new lamp
    })
    test('any symbol can be dropped anywhere: it is previewed and inserted, the user corrects a mistake afterwards', async ({page, app, backend}) => {
        await app.open(backend, withCircuit())
        await page.locator('#eds-palette-search').fill('Verdeelbord')
        const board = app.paletteButton('bord')
        const box = await app.drawn('S').boundingBox()
        await board.hover()
        await page.mouse.down()
        await page.mouse.move(box.x + 2, box.y + 2, {steps: 3})
        await page.mouse.move(box.x + box.width * 0.75, box.y + box.height / 2, {steps: 8})
        await expect(page.locator('#eds-drop-preview')).toBeVisible() // a board under a socket does not "fit", but it is not refused
        await page.mouse.up()
        await expect(page.locator('#eds-drop-preview')).toHaveCount(0)
        const saved = await app.save(backend)
        const types = (ns) => ns.flatMap((n) => [n.type, ...types(n.children)])
        expect(types(saved.een[0].tree).filter((t) => t === 'bord')).toHaveLength(2)
    })
})

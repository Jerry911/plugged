    clk(s, 3.2, 5.1)
    fireEvent.click(screen.getByText('Rechthoek'))
    clk(s, 3, 3)
    clk(s, 3.4, 3.2)
    fireEvent.change(name(), {target: {value: 'Raster'}})
    fireEvent.click(screen.getByText('Toevoegen'))
